function kz_plot_build_layout()
%KZ_PLOT_BUILD_LAYOUT Rebuild the saved GUIDE layout without runtime state.
% Developer utility: run after changing this layout definition. It keeps the
% original GUIDE figure metadata and saves the window with Visible='on'.
folder = fileparts(mfilename('fullpath'));
f = openfig(fullfile(folder, 'kz_plot.fig'), 'new', 'invisible');
cleanup = onCleanup(@() delete(f));
delete(allchild(f));
guidata(f, []);
set(f, 'Units', 'pixels', 'Position', [150 120 440 280], ...
    'Name', 'kz_plot', 'NumberTitle', 'off', 'Resize', 'off', ...
    'MenuBar', 'none', 'ToolBar', 'none', 'Color', [0.96 0.96 0.96]);
left = uipanel(f, 'Units', 'pixels', 'Position', [5 38 213 237], ...
    'Title', 'Cut parameters', 'FontSize', 8, 'BackgroundColor', [0.96 0.96 0.96]);
right = uipanel(f, 'Units', 'pixels', 'Position', [223 38 212 237], ...
    'Title', 'Curve manager', 'FontSize', 8, 'BackgroundColor', [0.96 0.96 0.96]);
addEntry(left, 199, 'Figure number', 'FigNum', '2010', '', ...
    'Target MATLAB figure number.');
addEntry(left, 178, 'Photon energy (eV)', 'hv', '60', 'hv_Callback', ...
    'Photon energy. The slider and this field stay synchronized.');
makeControl(left, 'slider', 'hvSlider', '', [6 158 136 17], ...
    'hvSlider_Callback', 'Min', 0, 'Max', 200, 'Value', 60, ...
    'SliderStep', [1/200 1/200], 'TooltipString', 'Photon energy in 1 eV steps.');
makeControl(left, 'text', 'sliderRange', '0 - 200 eV', [146 156 62 17], '');
addEntry(left, 137, 'Work function (eV)', 'w', '4.5', '', 'Sample work function.');
addEntry(left, 116, 'Inner potential (eV)', 'V0', '15', '', ...
    'Inner potential in the free-electron final-state model.');
addEntry(left, 95, 'Theta start (deg)', 'edit9', '-15', '', 'Starting emission angle.');
addEntry(left, 74, 'Theta end (deg)', 'edit10', '15', '', 'Ending emission angle.');
addEntry(left, 53, 'Theta step (deg)', 'thetaStep', '1', '', ...
    'Positive angular spacing. The final endpoint is always included.');
addEntry(left, 32, 'Line width (pt)', 'lineWidth', '1.5', '', 'Overlay line width.');
makeControl(left, 'text', '', 'Curve color', [6 11 114 17], '');
makeControl(left, 'popupmenu', 'curveColor', ...
    {'Green','Blue','Orange','Purple','Black'}, [124 8 78 20], '');
makeControl(right, 'text', 'curveCount', 'Attached curves (0)', [6 199 198 17], '');
makeControl(right, 'listbox', 'curveList', {'No attached curves'}, ...
    [6 43 198 154], 'curveList_Callback', 'BackgroundColor', 'white', ...
    'Min', 0, 'Max', 1, 'Value', 1);
makeControl(right, 'text', '', ...
    {'Select, edit fields, then Update.'; ...
    'Refresh after closing target figures.'}, ...
    [6 5 198 32], '');
makeControl(f, 'pushbutton', 'pushbutton1', 'Add curve', [5 17 100 19], ...
    'pushbutton1_Callback');
makeControl(f, 'pushbutton', 'updateCurve', 'Update', [223 17 76 19], ...
    'updateCurve_Callback', 'TooltipString', 'Update the selected curve.');
makeControl(f, 'pushbutton', 'deleteCurve', 'Delete', [303 17 76 19], ...
    'deleteCurve_Callback', 'TooltipString', 'Delete the selected curve and its label.');
makeControl(f, 'pushbutton', 'refreshCurves', 'Refresh', [383 17 52 19], ...
    'refresh_Callback');
makeControl(f, 'text', 'statusText', 'Set parameters and click Add curve.', ...
    [5 0 430 14], '');
% Saving a figure opened invisibly would otherwise hide subsequent launches.
set(f, 'Visible', 'on');
savefig(f, fullfile(folder, 'kz_plot.fig'));
end

function addEntry(parent, y, label, tag, value, callback, tooltip)
makeControl(parent, 'text', '', label, [6 y 114 17], '');
makeControl(parent, 'edit', tag, value, [124 y 78 19], callback, ...
    'BackgroundColor', 'white', 'TooltipString', tooltip);
end

function h = makeControl(parent, style, tag, label, position, callback, varargin)
h = uicontrol(parent, 'Style', style, 'Tag', tag, 'String', label, ...
    'Units', 'pixels', 'Position', position, 'FontSize', 8, varargin{:});
if strcmp(style, 'text')
    set(h, 'HorizontalAlignment', 'left', 'BackgroundColor', [0.96 0.96 0.96]);
end
if ~isempty(callback)
    set(h, 'Callback', @(s,e) kz_plot(callback, s, e, guidata(s)));
end
end
